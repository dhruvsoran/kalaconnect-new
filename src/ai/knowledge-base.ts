export function retrieveContext(query: string, topK = 4): string {
  const lowerQuery = query.toLowerCase();
  const keywords = lowerQuery.split(/\s+/).filter(w => w.length > 2);

  const scored = KNOWLEDGE_BASE.map(item => {
    let score = 0;
    const searchText = (item.title + ' ' + item.content + ' ' + item.tags.join(' ')).toLowerCase();
    for (const kw of keywords) {
      if (searchText.includes(kw)) score += 1;
      if (item.tags.some(t => t.includes(kw))) score += 2;
      if (item.title.toLowerCase().includes(kw)) score += 3;
    }
    return { item, score };
  });

  scored.sort((a, b) => b.score - a.score);
  const relevant = scored.filter(s => s.score > 0).slice(0, topK);

  if (relevant.length === 0) return '';

  return relevant.map(r => `## ${r.item.title}\n${r.item.content}`).join('\n\n---\n\n');
}

